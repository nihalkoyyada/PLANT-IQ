    def suggest_batch(
        self,
        headers: Sequence[str],
        sample_data: Optional[Dict[str, List[Any]]] = None,
        threshold: Optional[float] = None,
    ) -> BatchMappingResult:
        """Synchronously suggest mappings for a list of column headers."""
        start_time = time.perf_counter()
        suggestions: List[MappingSuggestion] = []

        for h in headers:
            samples = sample_data.get(h) if sample_data else None
            sug = self.suggest_header(h, sample_values=samples, threshold=threshold)
            suggestions.append(sug)

        return self._build_batch_result(suggestions, start_time)

    async def suggest_batch_async(
        self,
        headers: Sequence[str],
        sample_data: Optional[Dict[str, List[Any]]] = None,
        threshold: Optional[float] = None,
    ) -> BatchMappingResult:
        """Asynchronously suggest mappings for a list of column headers concurrently."""
        start_time = time.perf_counter()
        tasks = []

        for h in headers:
            samples = sample_data.get(h) if sample_data else None
            tasks.append(self.suggest_header_async(h, sample_values=samples, threshold=threshold))

        suggestions: List[MappingSuggestion] = await asyncio.gather(*tasks)
        return self._build_batch_result(suggestions, start_time)

    def _build_batch_result(
        self, suggestions: List[MappingSuggestion], start_time: float
    ) -> BatchMappingResult:
        """Aggregate suggestions list into BatchMappingResult summary."""
        duration_ms = (time.perf_counter() - start_time) * 1000.0
        fuzzy_count = sum(1 for s in suggestions if s.source in ("exact", "fuzzy"))
        llm_count = sum(1 for s in suggestions if s.source == "llm")
        unmapped_count = sum(1 for s in suggestions if s.source == "unmapped" or s.suggested_canonical_key is None)
        avg_conf = (
            sum(s.confidence_score for s in suggestions) / len(suggestions)
            if suggestions
            else 0.0
        )

        return BatchMappingResult(
            suggestions=suggestions,
            total_columns=len(suggestions),
            fuzzy_matches_count=fuzzy_count,
            llm_fallbacks_count=llm_count,
            unmapped_count=unmapped_count,
            average_confidence=round(avg_conf, 3),
            duration_ms=round(duration_ms, 2),
        )

    # Convenience method aliases
    suggest = suggest_header
    suggest_async = suggest_header_async

    # -----------------------------------------------------------------------
    # Tier 2 LLM Prompting & Execution
    # -----------------------------------------------------------------------

    async def _query_llm_fallback(
        self,
        raw_header: str,
        sample_values: Optional[List[Any]],
        top_candidates: List[Tuple[str, float]],
    ) -> Optional[MappingSuggestion]:
        """Construct targeted prompt and deduce canonical key via LLM provider."""
        provider = self._get_provider()
        if not provider:
            return None

        # Build concise catalog of canonical signals
        catalog_lines = [
            f"- {k}: {m.display_name} ({m.unit}) â€” {m.description}"
            for k, m in CANONICAL_SIGNALS.items()
        ]
        catalog_str = "\n".join(catalog_lines)

        system_prompt = (
            "You are an expert Solar PV SCADA Data Engineer for PlantIQ.\n"
            "Your objective is to map an ambiguous, abbreviated, or foreign telemetry header to our canonical signal dictionary.\n"
            "Here is the authoritative catalog of canonical keys:\n"
            f"{catalog_str}\n\n"
            "Strict Output Format: Respond ONLY with a valid JSON object matching this schema:\n"
            "{\n"
            '  "suggested_canonical_key": "<canonical_key_or_null>",\n'
            '  "confidence_score": <float between 0.0 and 1.0>,\n'
            '  "reasoning": "<concise explanation>"\n'
            "}\n"
            "If the column is unrelated to solar telemetry or cannot be mapped, set suggested_canonical_key to null."
        )

        sample_str = f"Sample values: {sample_values[:5]}" if sample_values else "Sample values: None available"
        candidates_str = ", ".join(f"{c[0]} ({c[1]:.1%})" for c in top_candidates)

        user_content = (
            f"Header to map: '{raw_header}'\n"
            f"{sample_str}\n"
            f"Top fuzzy heuristic candidates: {candidates_str}\n\n"
            "Deduce the correct canonical key."
        )

        try:
            response: ProviderResponse = await provider.chat(
                messages=[Message(role="user", content=user_content)],
                system=system_prompt,
                temperature=0.0,
                timeout=15.0,
            )

            raw_text = response.text.strip()
            # Extract JSON from response block
            match = re.search(r"\{.*\}", raw_text, re.DOTALL)
            if not match:
                return None

            payload = json.loads(match.group(0))
            suggested_key = payload.get("suggested_canonical_key")
            conf = float(payload.get("confidence_score", 0.70))
            reasoning = payload.get("reasoning", "Deducted via LLM semantic analysis.")

            # Validate that suggested key is an active canonical signal
            if suggested_key and suggested_key in CANONICAL_SIGNALS:
                return MappingSuggestion(
                    raw_header=raw_header,
                    suggested_canonical_key=suggested_key,
                    confidence_score=round(conf, 3),
                    source="llm",
                    reasoning=f"LLM Fallback: {reasoning}",
                    alternative_candidates=top_candidates,
                )
            elif suggested_key is None:
                return MappingSuggestion(
                    raw_header=raw_header,
                    suggested_canonical_key=None,
                    confidence_score=round(conf, 3),
                    source="unmapped",
                    reasoning=f"LLM Classification: {reasoning}",
                    alternative_candidates=top_candidates,
                )
        except Exception:
            return None

        return None


