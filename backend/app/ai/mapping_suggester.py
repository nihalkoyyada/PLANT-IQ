def suggest_mappings(
    headers: Sequence[str],
    sample_data: Optional[Dict[str, List[Any]]] = None,
    threshold: float = 0.80,
    provider: Optional[BaseProvider] = None,
) -> BatchMappingResult:
    """Convenience functional wrapper to suggest column mappings for a dataset."""
    suggester = MappingSuggester(provider=provider, default_threshold=threshold)
    return suggester.suggest_batch(headers, sample_data=sample_data, threshold=threshold)


