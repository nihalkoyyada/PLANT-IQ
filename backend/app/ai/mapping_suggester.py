# ---------------------------------------------------------------------------
# Header Normalization Helper
# ---------------------------------------------------------------------------


def normalize_header_text(header: str) -> str:
    """Normalize header string: split camelCase and replace delimiters with spaces."""
    # Split camelCase: e.g. "activePower" -> "active Power"
    s = re.sub(r"([a-z])([A-Z])", r"\1 \2", header)
    # Replace symbols and delimiters with space
    s = re.sub(r"[\s_\-\.\/:\(\)\[\]\^]+", " ", s)
    return s.strip().lower()


# ---------------------------------------------------------------------------
# Hybrid Mapping Suggester Engine
# ---------------------------------------------------------------------------


class MappingSuggester:
    """Two-tier hybrid column mapping suggestion engine."""

    def __init__(
        self,
        provider: Optional[BaseProvider] = None,
        default_threshold: float = 0.80,
        enable_llm_fallback: bool = True,
        llm_provider: Optional[BaseProvider] = None,
        fuzzy_threshold: Optional[float] = None,
    ) -> None:
        """Initialize suggester with an optional LLM provider for Tier 2 fallback."""
        self._provider = provider if provider is not None else llm_provider
        self.default_threshold = (
            fuzzy_threshold if fuzzy_threshold is not None else default_threshold
        )
        self.enable_llm_fallback = enable_llm_fallback

    def _get_provider(self) -> Optional[BaseProvider]:
        """Lazy load or return configured LLM provider if fallback is enabled."""
        if not self.enable_llm_fallback:
            return None
        if self._provider is not None:
            return self._provider
        try:
            self._provider = get_llm_provider()
            return self._provider
        except Exception:
            # If no provider can be initialized (e.g. offline without API key), provider remains None
            return None

    def _run_sync(self, coro: Coroutine[Any, Any, _T]) -> _T:
        """Run an async coroutine synchronously, safe in active or inactive event loops."""
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = None

        if loop is not None and loop.is_running():
            import concurrent.futures

            with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
                return pool.submit(asyncio.run, coro).result()
        else:
            return asyncio.run(coro)

    def suggest_header(
        self,
        raw_header: str,
        sample_values: Optional[List[Any]] = None,
        threshold: Optional[float] = None,
    ) -> MappingSuggestion:
        """Synchronously suggest canonical mapping for a single header (Tier 1 -> Tier 2 sync fallback)."""
        active_threshold = threshold if threshold is not None else self.default_threshold
        norm_header = normalize_header_text(raw_header)

        # Empty or non-alphanumeric header check
        if not norm_header:
            return MappingSuggestion(
                raw_header=raw_header,
                suggested_canonical_key=None,
                confidence_score=0.0,
                source="unmapped",
                reasoning=f"Header '{raw_header}' contains no alphanumeric tokens.",
            )

        # -------------------------------------------------------------------
        # Fast Path: Exact Match against key or synonyms
        # -------------------------------------------------------------------
        for key, meta in CANONICAL_SIGNALS.items():
            if norm_header == normalize_header_text(key):
                return MappingSuggestion(
                    raw_header=raw_header,
                    suggested_canonical_key=key,
                    confidence_score=1.0,
                    source="exact",
                    reasoning=f"Exact match with canonical key '{key}'.",
                )
            for syn in meta.synonyms:
                if norm_header == normalize_header_text(syn):
                    return MappingSuggestion(
                        raw_header=raw_header,
                        suggested_canonical_key=key,
                        confidence_score=1.0,
                        source="exact",
                        reasoning=f"Exact match with domain synonym '{syn}' for '{key}'.",
                    )

        # -------------------------------------------------------------------
        # Tier 1: Fuzzy String Similarity via rapidfuzz
        # -------------------------------------------------------------------
        candidates_scores: List[Tuple[str, float]] = []

        for key, meta in CANONICAL_SIGNALS.items():
            best_score = 0.0
            # Test against key itself
            key_norm = normalize_header_text(key)
            score_key = max(
                fuzz.token_sort_ratio(norm_header, key_norm),
                fuzz.ratio(norm_header, key_norm),
                fuzz.partial_ratio(norm_header, key_norm) * 0.90,
            )
            best_score = max(best_score, score_key)

            # Test against synonyms
            for syn in meta.synonyms:
                syn_norm = normalize_header_text(syn)
                score_syn = max(
                    fuzz.token_sort_ratio(norm_header, syn_norm),
                    fuzz.ratio(norm_header, syn_norm),
                )
                best_score = max(best_score, score_syn)

            normalized_score = round(best_score / 100.0, 3)
            candidates_scores.append((key, normalized_score))

        # Sort candidates descending by score
        candidates_scores.sort(key=lambda x: x[1], reverse=True)
        top_key, top_score = candidates_scores[0]
        alternatives = candidates_scores[1:4]

        # If fuzzy match is confident (>= threshold), return Tier 1 suggestion
        if top_score >= active_threshold:
            return MappingSuggestion(
                raw_header=raw_header,
                suggested_canonical_key=top_key,
                confidence_score=top_score,
                source="fuzzy",
                reasoning=f"High-confidence fuzzy string match ({top_score:.1%}) with '{top_key}'.",
                alternative_candidates=alternatives,
            )

        # -------------------------------------------------------------------
        # Tier 2: LLM Fallback (Sync runner)
        # -------------------------------------------------------------------
        provider = self._get_provider()
        if provider is not None:
            try:
                llm_suggestion = self._run_sync(
                    self._query_llm_fallback(
                        raw_header=raw_header,
                        sample_values=sample_values,
                        top_candidates=candidates_scores[:4],
                    )
                )
                if llm_suggestion:
                    return llm_suggestion
            except Exception:
                pass  # Fall through to unmapped if LLM fails

        # Fallback when LLM not available or cannot deduce mapping
        return MappingSuggestion(
            raw_header=raw_header,
            suggested_canonical_key=None,
            confidence_score=top_score,
            source="unmapped",
            reasoning=f"Header '{raw_header}' could not be reliably mapped to any canonical signal.",
            alternative_candidates=alternatives,
        )

