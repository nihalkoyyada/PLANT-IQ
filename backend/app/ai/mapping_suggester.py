MappingSource = Literal["exact", "fuzzy", "llm", "unmapped"]


@dataclass(frozen=True)
class MappingSuggestion:
    """Individual column mapping recommendation with confidence score."""

    raw_header: str
    suggested_canonical_key: Optional[str]
    confidence_score: float  # Normalized 0.0 to 1.0
    source: MappingSource
    reasoning: Optional[str] = None
    alternative_candidates: List[Tuple[str, float]] = field(default_factory=list)

    @property
    def is_mapped(self) -> bool:
        """Return True if a canonical key was successfully assigned."""
        return self.suggested_canonical_key is not None

    def to_dict(self) -> Dict[str, Any]:
        """Convert suggestion to JSON-serializable dictionary."""
        return asdict(self)


@dataclass(frozen=True)
class BatchMappingResult:
    """Batch mapping evaluation across all headers of a dataset."""

    suggestions: List[MappingSuggestion]
    total_columns: int
    fuzzy_matches_count: int
    llm_fallbacks_count: int
    unmapped_count: int
    average_confidence: float
    duration_ms: float

    def to_dict(self) -> Dict[str, Any]:
        """Convert result to JSON-serializable dictionary."""
        return asdict(self)


